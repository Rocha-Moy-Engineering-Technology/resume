import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

interface Evidence {
  title: string;
  status: string;
  image: string;
}

function htmlText(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

export default async function writeEvidenceGallery(): Promise<void> {
  const outputRoot = process.env.CONTRACTOR_SITE_E2E_ROOT;
  if (!outputRoot) throw new Error('Site evidence output directory missing');
  const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
  const gallery = join(projectRoot, 'evidence_gallery');
  const directory = join(outputRoot, 'screenshots');
  await mkdir(directory, { recursive: true });
  const files = (await readdir(directory)).filter((file) =>
    file.endsWith('.json')
  );
  const evidence = await Promise.all(
    files.map(async (file): Promise<Evidence> => {
      return JSON.parse(await readFile(join(directory, file), 'utf8'));
    })
  );
  evidence.sort((left, right) => left.title.localeCompare(right.title));
  const cards = evidence.map((item) => {
    const image = relative(gallery, join(directory, item.image));
    return `<article><h2>${htmlText(item.title)}</h2><p>${htmlText(item.status)}</p><a href="${htmlText(image)}"><img src="${htmlText(image)}" alt="${htmlText(item.title)}" loading="lazy" /></a></article>`;
  });
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" /><title>Contractor Site Headless Evidence</title><style>body { font: 16px system-ui; margin: 2rem; color: #171717; background: #f4f4f4; } main { display: grid; grid-template-columns: repeat(auto-fit, minmax(280px, 1fr)); gap: 1rem; } article { padding: 1rem; border: 1px solid #bbb; background: white; } h2 { font-size: 1rem; } img { display: block; width: 100%; max-height: 32rem; object-fit: contain; object-position: top; }</style></head><body><h1>Contractor Site Headless Evidence</h1><p>Generated by the Playwright suite. Screenshots remain in the agent's temporary folder. Every contact request is intercepted; no message is sent.</p><main>${cards.join('')}</main></body></html>`;
  await mkdir(gallery, { recursive: true });
  await writeFile(
    join(gallery, 'index.html'),
    await format(html, { parser: 'html' })
  );
}
